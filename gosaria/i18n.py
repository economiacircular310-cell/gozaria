def t(lang: str, key: str, **kwargs) -> str:
    text = T.get(lang, T[DEFAULT_LANG]).get(key) or T[DEFAULT_LANG].get(key, key)
    return text.format(**kwargs) if kwargs and isinstance(text, str) else text


def page_url(page: str, lang: str) -> str:
    return PAGES[page][lang]


def other_lang(lang: str) -> str:
    return "en" if lang == "es" else "es"
